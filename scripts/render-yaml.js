#!/usr/bin/env node
/**
 * Writes render.yaml, the Render Blueprint for the public site as a free static site.
 *
 * The Content-Security-Policy carries the hash of the inline script, so the headers are
 * taken from the same code the Node server uses instead of being copied by hand.
 * The site is built the way Render builds it (STATIC_HOSTING=true, no data/ folder).
 *
 *   node scripts/render-yaml.js          → rewrite render.yaml
 *   node scripts/render-yaml.js --check  → exit 1 if render.yaml is out of date
 */
const fs = require('fs');
const os = require('os');
const path = require('path');
const { spawnSync } = require('child_process');

const ROOT = path.resolve(__dirname, '..');
const FILE = path.join(ROOT, 'render.yaml');
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'qadoqlab-render-'));

// Render clones the repository, so settings edited in the admin panel (data/) are not there.
const env = { ...process.env, STATIC_HOSTING: 'true', DATA_DIR: path.join(tmp, 'no-data') };
delete env.SITE_DOMAIN;
let build;
try {
  const out = path.join(tmp, 'site');
  const run = spawnSync(process.execPath, [path.join(ROOT, 'src', 'build.js'), `--out=${out}`], {
    env,
    encoding: 'utf8',
  });
  if (run.status !== 0) {
    process.stderr.write(run.stderr || run.stdout);
    process.exit(1);
  }
  build = JSON.parse(fs.readFileSync(path.join(out, '_build.json'), 'utf8'));
} finally {
  fs.rmSync(tmp, { recursive: true, force: true });
}

process.env.DATA_DIR = env.DATA_DIR;
const { BASE_HEADERS, buildCsp } = require('../server/http');

const csp = buildCsp({
  scriptHashes: build.scriptHashes,
  trustedTypes: true,
  mailtoForms: true,
  https: true, // Render serves every site over HTTPS
});
const headers = [
  ['/*', 'Content-Security-Policy', csp],
  ...Object.entries(BASE_HEADERS)
    .filter(([name]) => name !== 'Strict-Transport-Security')
    .map(([name, value]) => ['/*', name, value]),
  ['/*', 'Strict-Transport-Security', 'max-age=31536000'],
  // every file under /assets/ has a content hash in its name
  ['/assets/*', 'Cache-Control', 'public, max-age=31536000, immutable'],
];

const q = JSON.stringify; // a JSON string is a valid YAML double-quoted scalar
const yaml = [
  '# Render Blueprint: the public site as a free static site, without the Node server.',
  '# Generated by scripts/render-yaml.js (npm run render:yaml). Edit the script, not this file.',
  '# Forms work in e-mail mode here; online sending and the admin panel need the Node server.',
  'services:',
  '  - type: web',
  '    name: qadoqlab',
  '    runtime: static',
  '    buildCommand: node src/build.js',
  '    staticPublishPath: dist',
  '    pullRequestPreviewsEnabled: false',
  '    envVars:',
  '      - key: STATIC_HOSTING',
  '        value: "true"',
  '      - key: NODE_VERSION',
  '        value: "22"',
  '    headers:',
  ...headers.flatMap(([p, name, value]) => [
    `      - path: ${p}`,
    `        name: ${name}`,
    `        value: ${q(value)}`,
  ]),
  '',
].join('\n');

if (process.argv.includes('--check')) {
  const current = fs.existsSync(FILE) ? fs.readFileSync(FILE, 'utf8') : '';
  if (current !== yaml) {
    console.error('render.yaml is out of date: run npm run render:yaml');
    process.exit(1);
  }
  console.log('✓ render.yaml is up to date');
} else {
  fs.writeFileSync(FILE, yaml);
  console.log('✓ render.yaml written');
}
